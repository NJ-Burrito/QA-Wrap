/**
 * Generates ui/fonts.css from the Thmanyah .woff2 files staged at
 * work/ui-rework/shared/fonts/ (git-ignored — never present under extension/
 * as loose files).
 *
 * This script bakes each face into a base64 data:font/woff2 URI directly in
 * the @font-face rule, rather than shipping the .woff2 bytes as a file. No
 * subsetting, no modification of the font data - the base64 is the source
 * bytes, untouched.
 *
 * Run from extension/: `node tools/build-fonts.mjs`. Idempotent: re-running
 * against the same source files regenerates byte-for-byte the same output.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const EXT = path.resolve(HERE, '..');
const SRC = process.env.QAW_FONTS_DIR ? path.resolve(process.env.QAW_FONTS_DIR) : path.resolve(EXT, '..', 'work', 'fonts'); // folder with the Thmanyah .woff2 files
const OUT = path.join(EXT, 'ui', 'fonts.css');

// Decision 2 (research/138): Sans Regular/Medium/Bold + Serif Display
// Regular. UI rework round 2 (S1, DESIGN-SPEC §1.1) adds Serif Display 700
// for display moments (the review pane's numbers, the brand wordmark at
// state-word size) — +108,828 B of base64, ~533 KB total [A]. The four Serif
// Text weights and Black are still not shipped — nothing live needs them.
const FACES = [
  { file: 'thmanyahsans-Regular.woff2', family: 'Thmanyah Sans', weight: 400 },
  { file: 'thmanyahsans-Medium.woff2', family: 'Thmanyah Sans', weight: 500 },
  { file: 'thmanyahsans-Bold.woff2', family: 'Thmanyah Sans', weight: 700 },
  { file: 'thmanyahserifdisplay-Regular.woff2', family: 'Thmanyah Serif Display', weight: 400 },
  { file: 'thmanyahserifdisplay-Bold.woff2', family: 'Thmanyah Serif Display', weight: 700 },
];

const rules = FACES.map(({ file, family, weight }) => {
  const full = path.join(SRC, file);
  if (!fs.existsSync(full)) {
    console.error(`build-fonts: missing source file ${full}`);
    process.exit(1);
  }
  const b64 = fs.readFileSync(full).toString('base64');
  return `@font-face { font-family: '${family}'; font-style: normal; font-weight: ${weight}; font-display: swap; src: url('data:font/woff2;base64,${b64}') format('woff2'); }`;
}).join('\n');

const header = `/* QA Wrap — local-first QA toolkit in the ISTQB shape. */
/* The face, bundled.
 *
 * GENERATED by tools/build-fonts.mjs from the .woff2 files staged at
 * work/ui-rework/shared/fonts/ (git-ignored; never present under extension/
 * as loose files — regenerate with \`node tools/build-fonts.mjs\`, never
 * hand-edit this file).
 *
 * Every rule below carries the font bytes inline as a base64 data: URI
 * rather than a url('fonts/...') reference - no loose .woff2 ships under
 * ui/fonts/.
 *
 * Weights shipped (decision 2, research/138): Sans Regular/Medium/Bold, Serif
 * Display Regular (report title only) — nothing else the two live tabs need.
 *
 * font-display: swap, not block: a base64 face this size loads with the
 * stylesheet, so a flash of the fallback face is the honest trade until the
 * real one arrives.
 */

`;

fs.writeFileSync(OUT, header + rules + '\n');
console.log(`build-fonts: wrote ${OUT} (${(fs.statSync(OUT).size / 1024).toFixed(1)} KB)`);
