/* QA Wrap — local-first QA toolkit in the ISTQB shape. */
/**
 * Build the vendored Public Suffix List snapshot (D3 of docs/decisions/2026-11-10-network-filter-and-click-labels.md).
 *
 *   node tools/build-psl.mjs <public_suffix_list.dat>     writes vendor/psl-data.js and the PSL block of content/page-hooks.js
 *   node tools/build-psl.mjs --check                      exits 1 when the two copies differ from each other
 *
 * Source: https://publicsuffix.org/list/public_suffix_list.dat (MPL-2.0). Vendored, never fetched at runtime.
 * Compact form: `tld:rest,rest,!exception;` per top-level label, host names in punycode. One-label rules are the
 * default rule and are not stored; `*.x` is stored as `*.x`, `!a.x` as `!a`.
 */
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import { domainToASCII, fileURLToPath } from 'node:url';

const EXT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = path.join(EXT, 'vendor', 'psl-data.js');
const HOOKS = path.join(EXT, 'content', 'page-hooks.js');
const BEGIN = '/*PSL:BEGIN*/';
const END = '/*PSL:END*/';

export function compact(dat) {
  const groups = new Map();
  for (let l of dat.split('\n')) {
    l = l.trim();
    if (!l || l.startsWith('//')) continue;
    const ex = l.startsWith('!');
    const wild = l.includes('*');
    const ascii = domainToASCII(l.replace(/^!/, '').replace(/^\*\./, 'x.')).replace(/^x\./, wild ? '*.' : '');
    const labels = ascii.split('.');
    const tld = labels.pop();
    const rest = labels.join('.');
    if (!rest && !ex) continue;
    if (!groups.has(tld)) groups.set(tld, []);
    groups.get(tld).push((ex ? '!' : '') + rest);
  }
  return [...groups].map(([t, v]) => `${t}:${v.join(',')}`).join(';');
}

const meta = (dat) => ({
  version: /^\/\/ VERSION: (.+)$/m.exec(dat)?.[1] ?? 'unknown',
  commit: /^\/\/ COMMIT: (\w+)$/m.exec(dat)?.[1] ?? 'unknown',
});

const hookBlock = (data) => `${BEGIN}\n  const PSL_DATA = ${JSON.stringify(data)};\n  ${END}`;

export function readHookData() {
  const src = fs.readFileSync(HOOKS, 'utf8');
  const i = src.indexOf(BEGIN);
  const j = src.indexOf(END);
  if (i < 0 || j < i) return null;
  const head = 'const PSL_DATA = ';
  const k = src.indexOf(head, i);
  if (k < 0 || k > j) return null;
  return JSON.parse(src.slice(k + head.length, src.lastIndexOf(';', j)));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = process.argv[2];
  if (arg === '--check') {
    const { PSL } = await import('../vendor/psl-data.js');
    const hook = readHookData();
    if (hook !== PSL.data) { console.error('vendor/psl-data.js and the PSL block of content/page-hooks.js differ'); process.exit(1); }
    console.log(`psl ok ${PSL.version} ${PSL.data.length} bytes`);
  } else {
    const dat = fs.readFileSync(arg, 'utf8');
    const data = compact(dat);
    const { version, commit } = meta(dat);
    const sha = crypto.createHash('sha256').update(dat).digest('hex');
    fs.writeFileSync(VENDOR, `/* QA Wrap — Public Suffix List snapshot, MPL-2.0. Generated by tools/build-psl.mjs; do not edit. */\nexport const PSL = ${JSON.stringify({ version, commit, sha256: sha, data })};\n`);
    const src = fs.readFileSync(HOOKS, 'utf8');
    const i = src.indexOf(BEGIN);
    const j = src.indexOf(END);
    if (i < 0 || j < i) throw new Error('no PSL block in content/page-hooks.js');
    fs.writeFileSync(HOOKS, src.slice(0, i) + hookBlock(data) + src.slice(j + END.length));
    console.log(`psl ${version} ${data.length} bytes sha256 ${sha}`);
  }
}
