/* QA Wrap — local-first QA toolkit in the ISTQB shape. */
/**
 * Builds ui/icons.js from the icon family checked into identity/icons/ui/
 * (UI round 2 S2, port of prototype/icons/build.mjs). The drawings themselves
 * are not authored here: identity/icons/ui/<id>.svg is a straight, final copy
 * of the prototype's already-verified drawings (python icons/_check.py PASS),
 * and identity/icons/ui/icons.json is the tracked manifest (id list, mirror
 * set, tool→icon map) copied from the prototype once. S11a added the Stage-2
 * ids (shape-*, event-*, key, dot, play) drawn straight into identity/icons/ui/
 * and `stage2_map` (which id replaces each old glyph). This script never reads
 * work/ (D2): only identity/icons/ui/.
 *
 * Run from extension/: `node tools/build-ui-icons.mjs`. Idempotent: re-running
 * against the same source files regenerates byte-for-byte the same output.
 * If the prototype redraws an icon, re-copy its .svg into identity/icons/ui/
 * and re-run this; there is no browser step.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const EXT = path.resolve(HERE, '..');
const SRC = path.resolve(EXT, '..', 'identity', 'icons', 'ui');
const OUT = path.join(EXT, 'ui', 'icons.js');

const meta = JSON.parse(fs.readFileSync(path.join(SRC, 'icons.json'), 'utf8'));
const UI = JSON.parse(fs.readFileSync(path.join(EXT, 'brand', 'brand.json'), 'utf8')).icons.ui; // s / m / l pixel sizes

const inner = {};
for (const icon of meta.icons) {
  const svg = fs.readFileSync(path.join(SRC, `${icon.id}.svg`), 'utf8');
  const body = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
  if (!body) throw new Error(`${icon.id}.svg: no <svg>...</svg> body`);
  inner[icon.id] = body[1].trim();
}

const mirror = meta.icons.filter((i) => i.mirror_rtl).map((i) => i.id);

fs.writeFileSync(
  OUT,
  `/* QA Wrap — local-first QA toolkit in the ISTQB shape. */
/**
 * The UI round 2 icon family (DESIGN-SPEC §0.2, §10). GENERATED by
 * tools/build-ui-icons.mjs from identity/icons/ui/: edit the drawings there,
 * then re-run.
 *
 *   UQAIcons              -> { [id]: '<inner svg markup>' }, drawn on the 24 grid
 *   UQAIconMirror          -> the ids that flip under [dir="rtl"]
 *   UQAIcon(id, {size, label}) -> '<svg class="icon [is-s|is-l] [mirror]" viewBox="0 0 24 24" ...>...</svg>' or ''
 */
window.UQAIcons = ${JSON.stringify(inner)};
window.UQAIconMirror = ${JSON.stringify(mirror)};
window.UQAIcon = function (id, o) {
  o = o || {};
  var body = window.UQAIcons[id];
  if (body == null) return '';
  var px = (o.size === ${UI.s} || o.size === 's') ? ${UI.s} : (o.size === ${UI.l} || o.size === 'l') ? ${UI.l} : ${UI.m};
  var cls = 'icon' + (px === ${UI.s} ? ' is-s' : px === ${UI.l} ? ' is-l' : '') + (window.UQAIconMirror.indexOf(id) >= 0 ? ' mirror' : '');
  var a11y = o.label
    ? 'role="img" aria-label="' + String(o.label).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;') + '"'
    : 'aria-hidden="true"';
  return '<svg class="' + cls + '" viewBox="0 0 24 24" width="' + px + '" height="' + px + '" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ' + a11y + ' focusable="false">' + body + '</svg>';
};
`,
);

console.log(`build-ui-icons.mjs: ${Object.keys(inner).length} ids, ${mirror.length} mirror in RTL -> ${path.relative(EXT, OUT)}`);
