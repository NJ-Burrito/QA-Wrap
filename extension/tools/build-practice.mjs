/* QA Wrap — local-first QA toolkit in the ISTQB shape. */
/**
 * Writes practice/practice.html, the packaged practice page, from game/index.html (Nader, 15 Oct 2026: the practice page is the Bug Hunt game).
 *
 *   node tools/build-practice.mjs           write it
 *   node tools/build-practice.mjs --check   exit 1 when the committed file is not what this would write (test-practice-game.mjs runs it)
 *
 * game/index.html stays the one source: the game server (npm run game) still serves it and its tests still read it. The extension page
 * differs in three ways, and only these: (1) asset addresses are relative to practice/ instead of the server root; (2) the run nonce is a
 * fixed value, because no server stamps this page and the page is already trusted by its own origin (content/bridge.js); (3) it carries the
 * recorder, because Chrome refuses executeScript on an extension page (the same files, in the same order, as site-access.js SITE_SCRIPTS),
 * (plus data-injector.js, the Nasty values tool, which is injected on demand elsewhere and executeScript cannot reach this page), behind mock-server.js, the in-extension stand-in for the game server's planted routes (it must load before page-hooks.js).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const EXT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const NONCE = '0'.repeat(32);
const RECORDER = ['selector-engine', 'replay-buffer', 'bridge', 'recorder', 'ui-host', 'mask', 'replay-recorder', 'vitals', 'checks', 'keymap', 'autopilot', 'data-injector'];

export function buildPracticeHtml(src) {
  let html = src
    .replace(/(href|src)="\/(ui|brand)\//g, '$1="../$2/')
    .replace(/(href|src)="\/(game\.css|shop\.css|game\.js)"/g, '$1="../game/$2"')
    .replace('content="__QAW_RUN__"', `content="${NONCE}"`);
  if (/(href|src)="\/[^/]/.test(html)) throw new Error('game/index.html has an address this script does not know how to move');
  html = html.replace(/<title>[^<]*<\/title>/, '<title>QA Wrap</title>'); // the bare brand name until game.js sets the page's own title in the tester's language (test-a11y-static)
  html = html.replace('<title>', '<script src="mock-server.js"></script>\n<link rel="stylesheet" href="../content/overlay.css">\n<script src="../content/page-hooks.js"></script>\n<title>');
  html = html.replace('</body>', `${RECORDER.map((f) => `<script src="../content/${f}.js"></script>`).join('\n')}\n</body>`);
  return `<!-- Generated by tools/build-practice.mjs from game/index.html. Edit that file, then run the script. -->\n${html}`;
}

const out = path.join(EXT, 'practice', 'practice.html');
const built = buildPracticeHtml(fs.readFileSync(path.join(EXT, 'game', 'index.html'), 'utf8'));
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(out) && fs.readFileSync(out, 'utf8') === built;
    console.log(same ? 'practice.html is in sync with game/index.html' : 'practice.html is OUT OF SYNC: run node tools/build-practice.mjs');
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(out, built);
  console.log(`wrote ${path.relative(EXT, out)} (${built.length} bytes)`);
}
