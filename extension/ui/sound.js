/* QA Wrap — local-first QA toolkit in the ISTQB shape. */
/**
 * The sound of the extension (replaced 6 Oct 2026, family A4 "Glass & Air": A3 with every sound given its own identity).
 *
 * Twenty-four short OGG files, original QA Wrap synthesis with CC0 recorded
 * layers (wine glass, pen, switch, tactile click; see ui/sfx/CREDITS.txt),
 * played through a small Web Audio player. Nothing is synthesised at play time.
 *
 * ── what is here ──────────────────────────────────────────────────────────
 *
 * Fifteen sound names in two scopes:
 *
 *   `core`   eight moments that say a result happened: wake, sleep, start,
 *            stop, shot (2 files), done, notice, error.
 *   `touch`  seven quiet answers to a press: tap (3 files), on, off, open,
 *            close, remove, copy (2 files each).
 *
 * A name with several files plays one at random and never the same one twice
 * in a row (round-robin by chance, so a repeated press does not sound like a
 * sample being retriggered).
 *
 * The setting "Which sounds" chooses the moments alone ("Results and alerts")
 * or both ("Every click").
 *
 * ── loudness ──────────────────────────────────────────────────────────────
 *
 * The files are already loudness-matched (BS.1770 active-span, per class: moments
 * about -16 to -20 LKFS, touch about -23 to -28, peaks at most -5 / -12 dBFS), so
 * every `trim` is 0 dB at volume 100, the one exception being `error`, +2.5 dB,
 * so that it stays the loudest and most distinct thing the product plays
 * (tools/sound-measure.mjs measured it 0.6 dB under `done`, 2.5 dB under `start`).
 * The measurements and the result are in ui/SOUNDS.md (generated by
 * tools/sound-doc.mjs) and are asserted by tools/test-sound.mjs.
 *
 * ── rules of play ─────────────────────────────────────────────────────────
 *
 *   1. The same sound is dropped inside 60 ms of itself.
 *   2. A touch sound is dropped when a different sound started within 120 ms.
 *      A moment is never dropped by that rule.
 *   3. At most three at once. Over that the oldest touch sound is released over
 *      about 15 ms; a moment is never cut.
 *   4. A hidden page, a disabled setting, a scope mismatch, `suspended` (set
 *      while the microphone is hot) and "files not decoded yet" all play nothing
 *      and return false. A hidden page hands a moment to the worker (UQA_CUE).
 *
 * The files are fetched from the extension's own origin and decoded once. This
 * script is injected into extension pages only; it is not in the service
 * worker's module graph and not in the in-page toolbar, so the files need no
 * web_accessible_resources entry and a host page cannot see them.
 */
(() => {
  if (window.UQASound) return;

  /* ══════════════════════════════════════════════════════ constants ═══ */

  const SFX_DIR = 'ui/sfx/';
  const MAX_SOUNDING = 3;
  const SAME_MS = 60;
  const CLASS_MS = 120;

  /* ══════════════════════════════════════════════════════ the sounds ══ */

  /**
   * name → { scope, files: [{ file, trim }] }. `trim` is dB at volume 100.
   * More than one file means one is picked at random, never the one just played.
   */
  const one = (f, trim = 0) => ({ file: f, trim });
  const SOUNDS = {
    wake: { scope: 'core', files: [one('wake.ogg')] },
    sleep: { scope: 'core', files: [one('sleep.ogg')] },
    start: { scope: 'core', files: [one('start.ogg')] },
    stop: { scope: 'core', files: [one('stop.ogg')] },
    shot: { scope: 'core', files: [one('shot.ogg'), one('shot2.ogg')] },
    done: { scope: 'core', files: [one('done.ogg')] },
    notice: { scope: 'core', files: [one('notice.ogg')] },
    error: { scope: 'core', files: [one('error.ogg', 2.5)] },
    tap: { scope: 'touch', files: [one('tap.ogg'), one('tap2.ogg'), one('tap3.ogg')] },
    on: { scope: 'touch', files: [one('on.ogg'), one('on2.ogg')] },
    off: { scope: 'touch', files: [one('off.ogg'), one('off2.ogg')] },
    open: { scope: 'touch', files: [one('open.ogg'), one('open2.ogg')] },
    close: { scope: 'touch', files: [one('close.ogg'), one('close2.ogg')] },
    remove: { scope: 'touch', files: [one('remove.ogg'), one('remove2.ogg')] },
    copy: { scope: 'touch', files: [one('copy.ogg'), one('copy2.ogg')] },
  };

  const SOUND_SCOPE = Object.fromEntries(Object.entries(SOUNDS).map(([id, s]) => [id, s.scope]));
  const FILES = [...new Set(Object.values(SOUNDS).flatMap((s) => s.files.map((f) => f.file)))];

  /**
   * Semantic events, mapped to sounds.
   *
   * The indirection is the point: a call site says *what happened*, never which
   * sound to make. Retuning never touches a call site.
   */
  const EVENTS = {
    'ui.tap': 'tap', 'ui.tap-soft': 'tap', 'ui.primary': 'tap', 'ui.quiet': 'tap',
    'ui.danger': 'remove', 'ui.tick': 'tap', 'ui.on': 'on', 'ui.off': 'off',
    'ui.check': 'on', 'ui.uncheck': 'off', 'ui.choose': 'tap', 'ui.slide': 'tap',
    'ui.open': 'open', 'ui.close': 'close', 'ui.tab': 'tap', 'ui.modal-open': 'open',
    'ui.modal-close': 'close', 'ui.copy': 'copy', 'ui.navigate': 'tap', 'ui.remove': 'remove',

    'switch.wake': 'wake', 'switch.sleep': 'sleep',
    'session.start': 'start', 'session.stop': 'stop',

    'capture.shot': 'shot', 'capture.full': 'shot',
    'record.start': 'start', 'record.stop': 'stop',

    'status.ok': 'copy', 'status.warn': 'notice', 'status.error': 'error', 'status.refused': 'notice',
    'scan.clean': 'done', 'scan.found': 'notice',

    'rule.armed': 'on', 'rule.fired': 'notice', 'value.inserted': 'copy',

    'jira.filed': 'done', 'jira.draft': 'copy', 'chat.sent': 'done',
    'export.done': 'done', 'file.saved': 'done', 'save.open': 'open', 'save.done': 'done',
    'team.card': 'tap',
    'harvest.done': 'done', 'autofill.done': 'done',
    'links.clean': 'done', 'links.broken': 'notice',
    'pick.added': 'tap', 'pick.all': 'copy',
    'diagram.node': 'tap', 'diagram.line': 'tap',
  };

  /**
   * What an element sounds like when nobody said.
   *
   * Ordered, first match wins. `data-sound="none"` names no sound, so it falls
   * out silently instead of reaching `.btn-primary` below it.
   */
  const ROLES = [
    ['[data-sound]', (el) => el.dataset.sound],
    ['.tool', () => 'ui.primary'],
    ['.tab, [role="tab"]', () => 'ui.tab'],
    ['.tool-info, .tool-more', (el) => (el.getAttribute('aria-expanded') === 'true' ? 'ui.close' : 'ui.open')],
    ['.btn-primary', () => 'ui.primary'],
    ['.btn-danger, .rule-drop, .dest-drop', () => 'ui.danger'],
    ['.btn-quiet, .btn-xs, .icon-btn, .link', () => 'ui.quiet'],
    ['summary', (el) => (el.parentElement?.open ? 'ui.close' : 'ui.open')],
    ['a[href]', () => 'ui.navigate'],
    ['button', () => 'ui.tap'],
    ['label.chip, label.scope-opt, .part', () => 'ui.choose'],
  ];

  /* ══════════════════════════════════════════════════════ the player ══ */

  let ctx = null;
  let master = null;

  let enabled = false;
  let volume = 0.7;
  let scope = 'core';
  let suspended = false;
  let clock = () => (typeof performance !== 'undefined' ? performance.now() : Date.now());

  const buffers = new Map(); // file name -> decoded AudioBuffer
  let loading = null;        // the one preload promise

  const db = (x) => Math.pow(10, x / 20);

  /** Volume 0-1 to gain: -20 dB at the bottom of the range, unity at the top, mute at 0. */
  const levelGain = (v) => (v <= 0 ? 0 : db(-20 * (1 - v)));

  /**
   * Build the context and the master gain, once.
   *
   * Playback must happen inside a user gesture (or be resumed from one): an
   * AudioContext created at load time starts suspended and stays silent, with no
   * error. Decoding does not need a context that can play, see `preload`.
   */
  function ensure() {
    if (ctx) return ctx;
    const Ctor = window.AudioContext || window.webkitAudioContext;
    if (!Ctor) return null;
    ctx = new Ctor({ latencyHint: 'interactive' });
    master = ctx.createGain();
    master.gain.value = levelGain(volume);
    master.connect(ctx.destination);
    return ctx;
  }

  /**
   * Fetch and decode every file, once. Resolves with how many are ready.
   *
   * Decoded on an OfflineAudioContext, so no real context is created (and no
   * autoplay warning is logged) until a person presses something. A decoded
   * buffer plays on any context. A file that fails is simply missing: its sound
   * returns false, and the next call to `preload` tries again.
   */
  function preload() {
    if (loading) return loading;
    loading = (async () => {
      let get;
      try {
        get = (file) => fetch(chrome.runtime.getURL(SFX_DIR + file));
      } catch { return buffers.size; }
      const Offline = window.OfflineAudioContext || window.webkitOfflineAudioContext;
      const decoder = Offline ? new Offline(2, 1, 44100) : null;
      await Promise.all(
        FILES.filter((f) => !buffers.has(f)).map(async (file) => {
          try {
            const res = await get(file);
            const bytes = await res.arrayBuffer();
            buffers.set(file, await (decoder || ensure()).decodeAudioData(bytes));
          } catch { /* decoration only; this file stays missing */ }
        })
      );
      if (buffers.size < FILES.length) loading = null; // allow a retry
      return buffers.size;
    })();
    return loading;
  }

  /** Start loading when the page is idle, so a click never pays for the fetch. */
  function preloadSoon() {
    if (loading || buffers.size === FILES.length) return;
    const go = () => { preload().catch(() => {}); };
    if (typeof window.requestIdleCallback === 'function') window.requestIdleCallback(go, { timeout: 2000 });
    else setTimeout(go, 50);
  }

  /* ─────────────────────────────────────────────────────── the rules ── */

  const recent = [];     // { id, scope, t } of sounds that played, wall clock ms
  const sounding = [];   // { scope, end, gain } by audio time
  const robin = {};      // which file of a multi-file sound played last

  function dropped(id, kind, t, force) {
    while (recent.length && t - recent[0].t > 1500) recent.shift();
    if (recent.some((r) => r.id === id && t - r.t < SAME_MS)) return true;
    if (kind === 'touch' && !force && recent.some((r) => r.id !== id && t - r.t < CLASS_MS)) return true;
    return false;
  }

  /** Make room under the three-sound cap. Returns false if a touch sound must give way. */
  function makeRoom(kind, now) {
    for (let i = sounding.length - 1; i >= 0; i--) if (sounding[i].end <= now) sounding.splice(i, 1);
    if (sounding.length < MAX_SOUNDING) return true;
    const oldest = sounding.findIndex((s) => s.scope === 'touch');
    if (oldest < 0) return kind === 'core';
    const [s] = sounding.splice(oldest, 1);
    s.gain.gain.setTargetAtTime(0, now, 0.004); // gone in about 15 ms
    return true;
  }

  /**
   * Play an event name or a sound name.
   *
   * Never throws, never awaits. A sound is decoration on an action, and an
   * action must not fail because a machine has no audio device.
   * Options: force (ignore scope: the settings page previews every sound).
   */
  function play(name, opts = {}) {
    if (!enabled || suspended || volume <= 0) return false;
    const id = EVENTS[name] || name;
    const def = SOUNDS[id];
    // A background tab making noise is a bug, not a feature. A moment is handed
    // to the worker instead, which plays it in the offscreen document (see
    // cueOp in background/media.js); the offscreen page is never hidden.
    if (typeof document !== 'undefined' && document.hidden) {
      if (def && def.scope === 'core') {
        try { chrome.runtime.sendMessage({ type: 'UQA_CUE', name }).catch(() => {}); } catch { /* no runtime */ }
      }
      return false;
    }
    if (!def) return false;
    if (def.scope === 'touch' && scope !== 'all' && !opts.force) return false;

    const t = clock();
    if (dropped(id, def.scope, t, !!opts.force)) return false;

    try {
      const n = def.files.length;
      const k = n < 2 ? 0 : robin[id] === undefined ? Math.floor(Math.random() * n) : (robin[id] + 1 + Math.floor(Math.random() * (n - 1))) % n;
      const pick = def.files[k];
      const buffer = buffers.get(pick.file);
      if (!buffer) { preloadSoon(); return false; }
      if (!ensure()) return false;
      if (ctx.state === 'suspended') ctx.resume().catch(() => {});
      const now = ctx.currentTime;
      if (!makeRoom(def.scope, now)) return false;

      const src = ctx.createBufferSource();
      src.buffer = buffer;
      const gain = ctx.createGain();
      gain.gain.value = db(pick.trim);
      src.connect(gain);
      gain.connect(master);
      src.start();

      robin[id] = k;
      recent.push({ id, scope: def.scope, t });
      sounding.push({ scope: def.scope, end: now + buffer.duration, gain });
      return true;
    } catch {
      return false;
    }
  }

  /* ══════════════════════════════════════════════════════ wiring ═══════ */

  /** Which sound this element makes, from the roles above. */
  function soundFor(el) {
    for (const [selector, pick] of ROLES) {
      const hit = el.closest?.(selector);
      if (hit) {
        const name = pick(hit);
        if (name) return name;
      }
    }
    return null;
  }

  /**
   * Wire a whole document at once.
   *
   * Delegated, so a control rendered later is covered the moment it appears.
   * The first press or key also creates and resumes the audio context, so the
   * first real cue is not the one that pays for starting it.
   */
  function wire(root = document) {
    if (root.__uqaSoundWired) return;
    root.__uqaSoundWired = true;

    const warm = () => {
      if (!enabled) return;
      try {
        if (ensure() && ctx.state === 'suspended') ctx.resume().catch(() => {});
        preloadSoon();
      } catch { /* decoration only */ }
    };
    root.addEventListener('pointerdown', warm, { capture: true, passive: true });
    root.addEventListener('keydown', warm, { capture: true, passive: true });

    root.addEventListener(
      'click',
      (event) => {
        const el = event.target;
        // A label wrapping a control fires click twice; the change handler owns those.
        if (el.closest?.('label')?.querySelector('input')) return;
        if (el.matches?.('input, select, textarea')) return;
        const name = soundFor(el);
        if (name) play(name);
      },
      true
    );

    root.addEventListener(
      'change',
      (event) => {
        const el = event.target;
        if (el.type === 'checkbox' || el.type === 'radio') {
          play(el.checked ? 'ui.check' : 'ui.uncheck');
        } else if (el.tagName === 'SELECT') {
          play('ui.choose');
        } else if (el.type === 'range') {
          play('ui.tick');
        }
      },
      true
    );

    // One tap per five steps, only when the value really changed.
    let lastSlide = null;
    root.addEventListener(
      'input',
      (event) => {
        const el = event.target;
        if (el.type !== 'range') return;
        const span = Number(el.max) - Number(el.min) || 100;
        const step = Math.round(Number(el.value) / Math.max(1, span / 20));
        if (step === lastSlide) return;
        lastSlide = step;
        play('ui.slide');
      },
      true
    );

    root.addEventListener(
      'toggle',
      (event) => {
        if (event.target.tagName === 'DETAILS') play(event.target.open ? 'ui.open' : 'ui.close');
      },
      true
    );
  }

  /* ══════════════════════════════════════════════════════ settings ═════ */

  /**
   * on: master switch. level: 0-1, the settings volume. scope: 'core' or 'all'
   * (a missed call site is harmless: it defaults to core). suspended: true
   * while the microphone is hot. clock: a test hook.
   */
  function configure({ on, level, scope: s, suspended: sus, clock: c } = {}) {
    if (typeof on === 'boolean') {
      enabled = on;
      if (on) preloadSoon();
    }
    if (typeof level === 'number') {
      volume = Math.max(0, Math.min(1, level));
      if (master) master.gain.value = levelGain(volume);
    }
    if (s === 'core' || s === 'all') scope = s;
    if (typeof sus === 'boolean') suspended = sus;
    if (typeof c === 'function') clock = c;
    return { enabled, volume, scope, suspended };
  }

  /** The sounds for a settings page: one row per name, with the events that reach it. */
  const catalogue = () =>
    Object.entries(SOUNDS).map(([id, s]) => ({
      id,
      scope: s.scope,
      files: s.files.map((f) => f.file),
      events: Object.keys(EVENTS).filter((e) => EVENTS[e] === id),
    }));

  window.UQASound = {
    play,
    configure,
    wire,
    soundFor,
    catalogue,
    preload,
    ready: () => preload(),
    SOUNDS,
    SOUND_SCOPE,
    EVENTS,
    ROLES,
    FILES,
    SFX_DIR,
  };
})();
