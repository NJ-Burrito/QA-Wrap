/* QA Wrap — local-first QA toolkit in the ISTQB shape. */
/**
 * The session as workbooks: the timeline and the session sheet as `.xlsx`.
 *
 * CSV is what a machine imports; a workbook is what a person filters. The
 * rows are the same as the CSV's — one per event, the same summary — with the
 * failures and the repro steps on sheets of their own, a bold frozen header
 * and an autofilter, so the question "show me only the 500s" is one click and
 * not a formula.
 */

import { buildXlsx } from './xlsx.js';
import { isTesterNote } from './events.js';
import { summarise, when as at } from './formats.js';
import { correlate, reproSteps, areasCovered, isFailure } from './artifact.js';
import { byPageOf } from './artifact-docs.js';
import { MAKER } from './provenance.js';
import { sessionIsArabic } from './docshell.js';

const iso = (ts) => (ts ? new Date(ts).toISOString().replace('T', ' ').slice(0, 19) : '');
/** T-066: one row per stored screenshot with its full SHA-256, so a workbook shows the same checksums as the other documents. */
const shaRows = (checksums) => Object.entries(checksums || {}).filter(([, h]) => h).map(([id, h]) => [`SHA-256 ${id}`, h]);
const lastOf = (events, kind) => [...events].reverse().find((e) => e.kind === kind) || null;

export function buildTimelineWorkbook(session, events, checksums = {}) {
  const chains = correlate(events);
  const count = (k) => events.filter((e) => e.kind === k).length;

  const summary = [
    ['Field', 'Value'],
    ['Charter', session.charter],
    ['Started', iso(session.startedAt)],
    ['Ended', iso(session.endedAt)],
    ['URL', session.startUrl || ''],
    ['Events', events.length],
    ['Interactions', count('dom')],
    ['Requests', count('net')],
    ['Failures', events.filter(isFailure).length],
    ['Screenshots', count('screenshot')],
    ['Generated by', MAKER.full],
    ['Session id', session.id],
    ...shaRows(checksums),
  ];

  const timeline = [
    ['at', 'kind', 'summary', 'url', 'status', 'ms', 'locator', 'failure'],
    ...events.map((ev) => [
      at(ev.ts, session.startedAt),
      ev.kind,
      summarise(ev),
      ev.url || ev.frameUrl || '',
      ev.status ?? '',
      ev.durationMs != null ? Math.round(ev.durationMs) : '',
      ev.locator ? `page.${ev.framePrefix || ''}${ev.locator}` : '',
      isFailure(ev) ? 'yes' : '',
    ]),
  ];

  const failures = [
    ['#', 'at', 'failure', 'cause', 'gap ms', 'url', 'siblings'],
    ...chains.map((c, i) => [
      i + 1,
      at(c.failure.ts, session.startedAt),
      summarise(c.failure),
      c.trigger ? summarise(c.trigger) : '(no action within the window)',
      c.trigger ? c.failure.ts - c.trigger.ts : '',
      c.failure.url || c.failure.frameUrl || '',
      c.siblings?.length || 0,
    ]),
  ];

  const steps = [['#', 'step'], ...reproSteps(events, byPageOf(session, events)).map((s, i) => [i + 1, s.replace(/^\d+\.\s*/, '')])];

  return buildXlsx(
    [
      { name: 'Summary', rows: summary, widths: [18, 80] },
      { name: 'Timeline', rows: timeline, widths: [10, 11, 70, 50, 8, 8, 50, 8] },
      { name: 'Failures', rows: failures, widths: [4, 10, 60, 50, 8, 50, 8] },
      { name: 'Steps', rows: steps, widths: [4, 90] },
    ],
    { title: `${session.charter}: timeline`, when: new Date(session.startedAt), ...(sessionIsArabic(session, events) ? { rtl: true } : {}) }
  );
}

export function buildSessionWorkbook(session, events, checksums = {}) {
  const notes = events.filter(isTesterNote);
  const perf = lastOf(events, 'perf');
  const a11y = lastOf(events, 'a11y');
  const links = lastOf(events, 'links');
  const env = session.env || {};
  const minutes = Math.max(1, Math.round(((session.endedAt || Date.now()) - session.startedAt) / 60000));

  const sheet = [
    ['Field', 'Value'],
    ['Charter', session.charter],
    ['Tester', session.tester || ''],
    ['Start', iso(session.startedAt)],
    ['End', iso(session.endedAt)],
    ['Duration (min)', minutes],
    ['URL', session.startUrl || ''],
    ['Platform', env.platform || ''],
    ['Viewport', env.viewport || ''],
    ['Language', env.language || ''],
    ['Browser', env.userAgent || ''],
    ['Generated by', MAKER.full],
    ...shaRows(checksums),
  ];
  const areas = [['Area', 'Events'], ...areasCovered(events).map((a) => [a.url, a.hits])];
  const noteRows = [['at', 'tag', 'text'], ...notes.map((n) => [at(n.ts, session.startedAt), n.tag || '', n.text || ''])];
  const metrics = [
    ['Metric', 'Value'],
    ['Interactions', events.filter((e) => e.kind === 'dom').length],
    ['Requests', events.filter((e) => e.kind === 'net').length],
    ['Failures', events.filter(isFailure).length],
    ['Screenshots', events.filter((e) => e.kind === 'screenshot').length],
    ['Bugs noted', notes.filter((n) => n.tag === 'bug').length],
    ['Questions', notes.filter((n) => n.tag === 'question').length],
    ['Accessibility issues', a11y ? a11y.total : ''],
    ['LCP (ms)', perf?.metrics?.lcp ?? ''],
    ['CLS', perf?.metrics?.cls ?? ''],
    ['INP (ms)', perf?.metrics?.inp ?? ''],
    ['Broken links', links ? links.broken.length : ''],
  ];

  return buildXlsx(
    [
      { name: 'Session', rows: sheet, widths: [18, 80] },
      { name: 'Areas', rows: areas, widths: [70, 10] },
      { name: 'Notes', rows: noteRows, widths: [10, 10, 90] },
      { name: 'Metrics', rows: metrics, widths: [24, 16] },
    ],
    { title: `${session.charter}: session sheet`, when: new Date(session.startedAt), ...(sessionIsArabic(session, events) ? { rtl: true } : {}) }
  );
}
