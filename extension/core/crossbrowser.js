const README = `# __TITLE__: cross-browser

Generated by QA Wrap from a session recorded on __DATE__.

The extension recorded this flow in Chromium and verified every locator against
the live page. It cannot run Firefox or WebKit: a browser extension cannot
start a process, so it wrote this instead. Playwright ships real builds of
both, so what runs here is the actual engine, not an emulation of one.

## Two commands

\`\`\`bash
npm install && npm run install:browsers
npm test
\`\`\`

The first command downloads the browser builds and takes a few minutes once.

## What to expect

The spec is the flow as recorded, so a failure in Chromium means the flow has
changed since it was recorded. A failure **only** in WebKit or Firefox is the
interesting case, and it is the reason this project exists:

- **Dates.** \`new Date("2026-08-27 10:00")\` parses in Chromium and returns
  Invalid Date in Safari. Every date bug found this way looks like a backend
  bug until it is run in WebKit.
- **Regular expressions.** Lookbehind and named groups arrived late in Safari.
- **Flexbox and grid gaps** resolve differently at fractional pixel sizes.
- **Input types.** \`<input type="date">\` renders and behaves differently in
  every one of the three.

## The locators

They were verified against the running page at capture time: each was checked
to match exactly one element before it was written here. That does not make them
permanent: a locator anchored to visible text will break when the text is
translated, and that break is real information.

## What this does not cover

The session as it was walked, and nothing else. It is a starting point for a
regression test, not a test plan. CTFL principle 2: exhaustive testing is
impossible, so what you choose to add matters more than what was recorded.
`;

/** r8-11-3: the exact variable names the spec reads, so a tester knows what to set before `npm test`. */
const secretsSection = (spec) => {
  const names = [...new Set(String(spec).match(/\b(?:QAW_SECRET_\w+|UQA_SECRET|UQA_UPLOAD_FILE)\b/g) || [])];
  const what = (n) => (n === 'UQA_UPLOAD_FILE' ? 'the path of the file to upload' : n === 'UQA_SECRET' ? 'the fallback value for every secret field' : 'the value of one secret field');
  return names.length ? `\n## Secrets and files\n\nThe recording never kept a secret value or an uploaded file. Set these environment variables before \`npm test\`:\n\n${names.map((n) => `- \`${n}\`: ${what(n)}`).join('\n')}\n` : '';
};

/** r8-11-2: a goto on the recorded origin becomes path + search + hash, so BASE_URL moves the whole run; a cross-origin goto stays absolute. */
const relativeGotos = (spec, origin) => (origin ? String(spec).replace(/\.goto\('((?:[^'\\]|\\.)*)'/g, (m, raw) => {
  try {
    const u = new URL(raw.replace(/\\(.)/g, '$1'));
    return u.origin === origin ? `.goto('${(u.pathname + u.search + u.hash).replace(/[\\']/g, '\\$&')}'` : m;
  } catch { return m; }
}) : spec);

/**
 * Build the whole project as a set of files.
 *
 * Returned as data rather than written, so the caller decides where it lands
 * and can show the tester what is about to be created first.
 *
 * @returns {Array<{path: string, content: string}>}
 */
export function crossBrowserProject(session, spec, { title } = {}) {
  const name = title || session.charter || 'recorded flow';
  const slug =
    name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 40) || 'session';

  let baseURL = '';
  try {
    baseURL = session.startUrl ? new URL(session.startUrl).origin : '';
  } catch {
    /* no usable origin */
  }

  // r9-11-2: one pass per template with a function replacer, so `$&` in a charter is text and a literal `__DATE__` in it is not filled again.
  const fillIn = (tpl, values) => tpl.replace(/__([A-Z_]+)__/g, (m, k) => (k in values ? values[k] : m));
  const started = new Date(session.startedAt);
  const date = (Number.isNaN(started.getTime()) ? new Date() : started).toISOString().slice(0, 10); // an imported session may have no start

  return [
    { path: 'playwright.config.ts', content: fillIn(CONFIG, { BASE_URL: baseURL }) },
    { path: 'package.json', content: fillIn(PACKAGE, { SLUG: slug }) },
    {
      path: 'README.md',
      content: fillIn(README, { TITLE: name, DATE: date }) + secretsSection(spec),
    },
    { path: `tests/${slug}.spec.ts`, content: relativeGotos(spec, baseURL) },
    {
      path: '.gitignore',
      content: 'node_modules/\ntest-results/\nplaywright-report/\nblob-report/\n',
    },
  ];
}

