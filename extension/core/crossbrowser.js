/**
 * Cross-browser testing, honestly.
 *
 * ── what an extension cannot do, said first ───────────────────────────────
 *
 * A Chrome extension cannot launch Firefox, cannot launch WebKit, and cannot
 * launch a second Chromium. It has no way to start a process. Nothing in the
 * extension APIs opens a browser, and no permission unlocks one — that is the
 * sandbox working as designed, not a gap to route around.
 *
 * It cannot honestly emulate another engine either. Spoofing the user-agent
 * string changes what a page is *told* and nothing about what actually runs:
 * the layout engine is still Blink, the JavaScript engine is still V8, the CSS
 * support is still Chrome's. A tool that offers a "Safari mode" which is Blink
 * wearing a Safari label will find no Safari bugs and will hide the fact that
 * you have not tested Safari — which is worse than not offering it.
 *
 * ── so what this does instead ─────────────────────────────────────────────
 *
 * Two things, both real:
 *
 *   **A window at a named size.** Viewport bugs are the most common
 *   cross-device failures and they need no other engine — a 360×640 window in
 *   Chrome finds a broken mobile layout exactly as well as a phone does. Real
 *   window, real reflow, no pretending.
 *
 *   **A runnable Playwright project.** This is the genuine route to WebKit and
 *   Gecko: Playwright ships real builds of both, and the session has already
 *   been turned into a spec with verified locators. So the extension writes the
 *   whole project — config, spec, package.json, and the two commands to run it
 *   — and the tester runs it outside the browser, where a browser can be
 *   launched. The extension does the part it can and hands over the part it
 *   cannot, rather than faking the join.
 */

