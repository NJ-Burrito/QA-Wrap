/* Generates every token format + the vector palette sheet from ONE source.
     node tools/tokens.mjs                                                    */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as S from './tokens.source.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = (rel, data) => {
  const p = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, data, 'utf8');
  console.log('  ' + rel);
};

const LINES = [
  `QA Wrap ${S.meta.version} - generated by tools/tokens.mjs. Do not edit by hand.`,
  `Edit tools/tokens.source.mjs and re-run.`,
];
const slashBanner = () => LINES.map(l => `// ${l}`).join('\n') + '\n';
const blockBanner = () => `/* ${LINES.join('\n   ')} */\n`;

/* Flatten to emit order. */
const rows = [];
for (const [k, v] of Object.entries(S.brand))    rows.push([`brand-${k}`, v, 'brand']);
for (const [k, v] of Object.entries(S.neutral))  rows.push([`n-${k}`, v, 'neutral']);
for (const [k, v] of Object.entries(S.surface))  rows.push([k, v, 'surface']);
for (const [k, v] of Object.entries(S.semantic)) rows.push([k, v, 'semantic']);

const GROUPS = {
  brand:    'Brand - expressive. Large surfaces, illustration, marketing.',
  neutral:  'One ramp, limestone to basalt. Warm grey in the middle, never a blue grey.',
  surface:  'Surfaces and rules.',
  semantic: 'UI states: the action, the four results, and the aliases that keep older CSS working.',
};

/* A value with no entry for a mode falls back to light. */
const val = (v, mode) => v[mode] ?? v.light;
const pick = (obj, mode) =>
  Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, val(v, mode)]));
const flatPalette = (mode) => ({
  ...pick(S.brand, mode),
  ...Object.fromEntries(Object.entries(S.neutral).map(([k, v]) => [`n${k}`, val(v, mode)])),
  ...pick(S.semantic, mode),
});

/* ------------------------------------------------------------------- CSS */
{
  const block = (mode, indent) => {
    let s = '', seen = null;
    for (const [name, v, group] of rows) {
      if (group !== seen) { s += `\n${indent}/* ${GROUPS[group]} */\n`; seen = group; }
      s += `${indent}--${name}: ${val(v, mode)};${v.use && mode === 'light' ? `  /* ${v.use} */` : ''}\n`;
    }
    return s;
  };
  const flat = (obj, prefix, indent) =>
    Object.entries(obj).map(([k, v]) => `${indent}--${prefix}${k}: ${v};`).join('\n');

  out('tokens/tokens.css',
`${blockBanner()}
:root {
${block('light', '  ')}
  /* Type */
  --display: ${S.type.display};
  --font: ${S.type.font};
  --mono: ${S.type.mono};

  /* Shape */
${flat(S.radius, 'r-', '  ')}

  /* Motion - honoured only when the viewer allows it, see the block below. */
${flat(S.motion, '', '  ')}

  --shadow-1: ${S.shadow[1].light};
  --shadow-2: ${S.shadow[2].light};
}

/* Dark is the same page under different light: only the values change. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block('dark', '    ')}
    --shadow-1: ${S.shadow[1].dark};
    --shadow-2: ${S.shadow[2].dark};
  }
}

/* Higher contrast: solid edges instead of the soft tint (F11). */
@media (prefers-contrast: more) {
  :root {
    --border: var(--text);
    --border-strong: var(--text);
  }
  .tool-row, .card {
    border-width: 1px;
  }
}

/* ── type scale — Thmanyah, one weight/tracking/leading triple per step
   (F23, F24); sizes are rem so the layout scales with the user's text-size
   setting (F25). ── */
:root {
${Object.entries(S.typeScale).map(([k, v]) => `  --t-${k}: ${v.size};
  --weight-${k}: ${v.weight};
  --track-${k}: ${v.track};
  --lead-${k}: ${v.lead};`).join('\n\n')}

  /* Spacing — rem, so it scales with text size. Hit targets stay px (F25). */
${Object.entries(S.spacing).map(([k, v]) => `  --sp-${k}: ${v};`).join('\n')}
}

/* Uppercase tracking is a Latin concern only — Arabic has no case. */
[lang='ar'] .micro,
[lang='ar'] [class*='micro'] {
  text-transform: none;
  letter-spacing: 0.01em;
}

/* An explicit choice always beats the OS. */
:root[data-theme="dark"] {
${block('dark', '  ')}
  --shadow-1: ${S.shadow[1].dark};
  --shadow-2: ${S.shadow[2].dark};
}

/* Reduced-motion is handled per-surface, by name, in each consumer's own
   motion system — never as a global \`*\` sledgehammer (F07). */
`);
}

/* ------------------------------------------------------------------ SCSS */
{
  let s = slashBanner(), seen = null;
  for (const [name, v, group] of rows) {
    if (group !== seen) { s += `\n// ${GROUPS[group]}\n`; seen = group; }
    s += `$${name}: ${v.light};\n`;
    if (v.dark && v.dark !== v.light) s += `$${name}--dark: ${v.dark};\n`;
  }
  s += `\n// Type\n$display: ${S.type.display};\n$font: ${S.type.font};\n$mono: ${S.type.mono};\n`;
  s += `\n// Shape\n` + Object.entries(S.radius).map(([k, v]) => `$r-${k}: ${v};`).join('\n') + '\n';
  s += `\n// Motion\n` + Object.entries(S.motion).map(([k, v]) => `$${k}: ${v};`).join('\n') + '\n';
  out('tokens/tokens.scss', s);
}

/* ------------------------------------------------------------------ JSON */
out('tokens/tokens.json', JSON.stringify({
  meta: S.meta,
  brand: S.brand, neutral: S.neutral, surface: S.surface, semantic: S.semantic,
  type: S.type, webfont: S.webfont, radius: S.radius, shadow: S.shadow, motion: S.motion,
}, null, 2) + '\n');

/* ------------------------------------------------------------------- ESM */
out('tokens/tokens.mjs',
`${slashBanner()}
export const meta = ${JSON.stringify(S.meta)};
export const light = ${JSON.stringify(flatPalette('light'), null, 2)};
export const dark = ${JSON.stringify(flatPalette('dark'), null, 2)};
export const type = ${JSON.stringify(S.type, null, 2)};
export const radius = ${JSON.stringify(S.radius, null, 2)};
export const motion = ${JSON.stringify(S.motion, null, 2)};
export const webfont = ${JSON.stringify(S.webfont)};

/** Resolve the palette for a mode: theme('dark').salsa */
export const theme = (mode = 'light') => ({ dark }[mode] || light);
export default { meta, light, dark, type, radius, motion, webfont, theme };
`);

/* ------------------------------------------------------------------- CJS */
out('tokens/tokens.cjs',
`${slashBanner()}
const light = ${JSON.stringify(flatPalette('light'), null, 2)};
const dark = ${JSON.stringify(flatPalette('dark'), null, 2)};
module.exports = {
  meta: ${JSON.stringify(S.meta)},
  light, dark,
  type: ${JSON.stringify(S.type, null, 2)},
  radius: ${JSON.stringify(S.radius, null, 2)},
  motion: ${JSON.stringify(S.motion, null, 2)},
  webfont: ${JSON.stringify(S.webfont)},
  theme: (mode = 'light') => ({ dark }[mode] || light),
};
`);

/* -------------------------------------------------------------- Tailwind */
out('tokens/tailwind.preset.cjs',
`${slashBanner()}// tailwind.config.js:
//   module.exports = { presets: [require('./identity/tokens/tailwind.preset.cjs')] }
// Pair it with tokens.css so the CSS variables actually exist at runtime.
const c = (name) => \`var(--\${name})\`;

module.exports = {
  theme: {
    extend: {
      colors: {
${Object.keys(S.brand).map(k => `        ${k}: c('brand-${k}'),`).join('\n')}
${Object.keys(S.semantic).map(k => `        '${k}': c('${k}'),`).join('\n')}
        paper: { ${Object.keys(S.neutral).map(k => `${k}: c('n-${k}')`).join(', ')} },
      },
      fontFamily: {
        display: [${JSON.stringify(S.type.display.split(',')[0].replace(/"/g, ''))}, 'sans-serif'],
        sans: [${JSON.stringify(S.type.font.split(',')[0].replace(/"/g, ''))}, 'sans-serif'],
        mono: [${JSON.stringify(S.type.mono.split(',')[0].replace(/"/g, ''))}, 'monospace'],
      },
      borderRadius: ${JSON.stringify(S.radius)},
      transitionTimingFunction: {
        brand: ${JSON.stringify(S.motion.ease)},
        pop: ${JSON.stringify(S.motion['ease-pop'])},
      },
    },
  },
};
`);

/* --------------------------------------------------- vector palette sheet */
{
  const W = 900, PAD = 34, SW = 132, GAP = 14, ROW = 176;
  const sections = [
    ['Brand', Object.entries(S.brand)],
    ['Semantic', Object.entries(S.semantic).filter(([k]) => !k.endsWith('-soft'))],
    ['Paper ramp', Object.entries(S.neutral).map(([k, v]) => [`n-${k}`, v])],
  ];
  const readable = (hex) => {
    const m = /^#([0-9a-f]{6})$/i.exec(hex);
    if (!m) return '#3A2A22';
    const n = parseInt(m[1], 16);
    const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map(v => {
      v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4);
    });
    return 0.2126 * r + 0.7152 * g + 0.0722 * b > 0.42 ? '#3A2A22' : '#FFFAF0';
  };

  let y = PAD + 30, body = '';
  for (const [title, entries] of sections) {
    body += `<text x="${PAD}" y="${y}" font-family="Lilita One, Arial Black, sans-serif" font-size="21" fill="#3A2A22">${title}</text>`;
    y += 18;
    entries.forEach(([name, v], i) => {
      const col = i % 5, row = Math.floor(i / 5);
      const x = PAD + col * (SW + GAP), yy = y + row * ROW;
      const hex = v.light;
      body += `<g>
    <rect x="${x}" y="${yy}" width="${SW}" height="88" rx="12" fill="${hex}" stroke="rgba(58,42,34,.18)"/>
    <text x="${x + 12}" y="${yy + 74}" font-family="DM Mono, monospace" font-size="12" fill="${readable(hex)}">${hex}</text>
    <text x="${x}" y="${yy + 108}" font-family="Nunito Sans, sans-serif" font-weight="800" font-size="12.5" fill="#3A2A22">${name}</text>
    <text x="${x}" y="${yy + 124}" font-family="DM Mono, monospace" font-size="9.5" fill="#8A7461">var(--${name})</text>
  </g>`;
    });
    y += Math.ceil(entries.length / 5) * ROW + 16;
  }
  const H = Math.round(y + PAD);
  out('palette/palette-sheet.svg',
`<!-- QA Wrap palette. Generated by tools/tokens.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="QA Wrap palette">
  <rect width="${W}" height="${H}" fill="#F7EBD6"/>
  <text x="${PAD}" y="${PAD + 4}" font-family="DM Mono, monospace" font-size="11" letter-spacing="2" fill="#8A7461">QA WRAP ${S.meta.version}</text>
  ${body}
</svg>
`);
}

console.log('\nTokens regenerated from tools/tokens.source.mjs');
